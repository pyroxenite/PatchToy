function bitmapToPath(rows) {
    // Merge horizontal runs into rects: M x y h w v 1 h -w z
    let d = '';
    for (let y = 0; y < rows.length; y++) {
        const row = rows[y];
        let x = 0;
        while (x < row.length) {
            if (row[x] === '#') {
                let w = 1;
                while (x + w < row.length && row[x + w] === '#') w++;
                d += `M${x} ${y}h${w}v1h-${w}z`;
                x += w;
            } else {
                x++;
            }
        }
    }
    return d;
}

export const ICON_NAMES = Object.keys(BITMAPS);

let spriteInjected = false;

/** Inject the SVG sprite into the document (idempotent). */
export function injectIconSprite() {
    if (spriteInjected || typeof document === 'undefined') return;
    if (document.getElementById('pt-icon-sprite')) {
        spriteInjected = true;
        return;
    }
    const symbols = ICON_NAMES.map(name =>
        `<symbol id="i-${name}" viewBox="0 0 16 16"><path d="${bitmapToPath(BITMAPS[name])}"/></symbol>`
    ).join('');
    const wrap = document.createElement('div');
    wrap.innerHTML = `<svg id="pt-icon-sprite" xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">${symbols}</svg>`;
    document.body.insertBefore(wrap.firstChild, document.body.firstChild);
    spriteInjected = true;
}

/** SVG markup for an icon. */
export function icon(name, { size = 16, className = '' } = {}) {
    return `<svg class="pt-i ${className}" width="${size}" height="${size}" viewBox="0 0 16 16" aria-hidden="true" focusable="false"><use href="#i-${name}"/></svg>`;
}

/** Create an icon as a DOM element. */
export function iconEl(name, opts) {
    const t = document.createElement('template');
    t.innerHTML = icon(name, opts);
    return t.content.firstChild;
}

// Inject as soon as the module loads so static markup in index.html resolves.
if (typeof document !== 'undefined') {
    if (document.body) injectIconSprite();
    else document.addEventListener('DOMContentLoaded', injectIconSprite, { once: true });
}
